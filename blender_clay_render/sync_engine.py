# -*- coding: utf-8 -*-
# engine/ = 仓库 video_studio/blender/ 的 vendored 镜像（云端与本地同一条引擎链）。
# 唯一正本在 video_studio/blender/——改引擎改那边，然后跑本脚本同步：
#   python sync_engine.py [--src D:/_globixai/video_studio/blender]
# 校验：ENGINE_SHA256.txt 逐文件 sha256 比对，漂移即列出。
import hashlib
import os
import shutil
import sys

FILES = ["scene_run.py", "render_scene.py", "blender_lib.py", "blender_resolve.py",
         "ensure_model.py", "fetch_glb.py", "director_spec.py"]
_HERE = os.path.dirname(os.path.abspath(__file__))
ENGINE = os.path.join(_HERE, "engine")
MANIFEST = os.path.join(ENGINE, "ENGINE_SHA256.txt")


def _sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main():
    src = os.path.abspath(sys.argv[sys.argv.index("--src") + 1]) if "--src" in sys.argv \
        else os.path.abspath(os.path.join(_HERE, "..", "..", "..", "..", "..", "video_studio", "blender"))
    check_only = "--check" in sys.argv
    missing = [f for f in FILES if not os.path.isfile(os.path.join(src, f))]
    if missing:
        print("源目录缺文件 %s: %s" % (src, missing)); return 2
    drift = []
    lines = []
    for f in FILES:
        sp, dp = os.path.join(src, f), os.path.join(ENGINE, f)
        s_sha = _sha(sp)
        lines.append("%s  %s" % (s_sha, f))
        if check_only:
            d_sha = _sha(dp) if os.path.isfile(dp) else ""
            if d_sha != s_sha:
                drift.append(f)
        else:
            os.makedirs(ENGINE, exist_ok=True)
            shutil.copy2(sp, dp)
    if check_only:
        if drift:
            print("engine/ 与正本漂移: %s——跑 sync_engine.py 同步" % drift); return 1
        print("engine/ 与正本一致 (%d 文件)" % len(FILES)); return 0
    with open(MANIFEST, "w", encoding="utf-8") as f:
        f.write("# generated by sync_engine.py — do not edit engine/ by hand\n")
        f.write("\n".join(lines) + "\n")
    print("synced %d files %s -> %s" % (len(FILES), src, ENGINE)); return 0


if __name__ == "__main__":
    sys.exit(main())
